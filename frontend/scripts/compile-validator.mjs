/**
 * Compile `shared/schema/circuit.schema.json` into a self-contained validator.
 *
 * Invoked by `shared/generate_bindings.py`, which owns the generation pipeline
 * and formats and newline-normalizes the result. It lives here rather than in
 * `shared/` because it imports Ajv, and Node resolves that from the frontend's
 * own `node_modules` -- the same reason the script reaches for `json2ts` and
 * `prettier` through `frontend/node_modules/.bin`. Nothing here imports project
 * source, so `shared/README.md`'s dependency rule still holds.
 *
 * **Ajv is a devDependency and nothing it produces depends on it at runtime.**
 * ADR-0008 section 1 measured that: the emitted code has no imports at all, and
 * costs about 6 KB gzipped against roughly 30 KB for shipping Ajv itself, which
 * would also have to compile the schema through `new Function` on every load.
 *
 * **One validator per operation subtype, not one for the whole document.**
 * `oneOf` plus `$ref` loses branch attribution in Ajv's error output --
 * `schemaPath` reads `#/additionalProperties` whichever branch produced it -- so
 * the branches that do *not* match report the fields they do not share as
 * unknown. A caller stripping those errors deletes a gate's `name`, `controls`
 * and `parameters`. Splitting by subtype and selecting on `kind` is what makes an
 * `additionalProperties` error mean what it says. See ADR-0008 section 2, and the
 * `$comment` on `Operation` in the schema.
 */

import { writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const [schemaPath, outputPath] = process.argv.slice(2);

if (schemaPath === undefined || outputPath === undefined) {
  console.error('usage: compile-validator.mjs <schema.json> <output.ts>');
  process.exit(1);
}

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

// `strict: false` because the schema carries OpenAPI's `discriminator`, which
// Ajv rejects as an unknown keyword rather than ignoring as an annotation.
// `allErrors` because stripping needs every unknown field, not just the first.
const ajv = new Ajv2020({
  strict: false,
  allErrors: true,
  code: { source: true, esm: true },
});

/*
  `format` is declared unvalidated rather than left to warn.

  JSON Schema treats `format` as an annotation unless a validator opts in, so
  ignoring it is the default behaviour -- but Ajv warns about it on every
  generation, and a warning nobody acts on is worse than a decision nobody
  wrote down. Registering it properly means `ajv-formats`, whose `date-time`
  is a function rather than a regex, so the compiled output would import it at
  runtime and lose the property that justifies compiling at all.

  The consequence is a real divergence: Pydantic parses `createdAt` as a
  datetime and rejects a malformed one, and this validator accepts it. It is
  confined to `Metadata`, which carries nothing semantic, and the backend
  remains the authority on any document it is given. Recorded in Frontend.md.
*/
for (const format of ['date-time']) ajv.addFormat(format, true);

const { propertyName, mapping } = schema.$defs.Operation.discriminator;
const kinds = Object.keys(mapping);

// The document with its operations left as an opaque array. Each operation is
// checked separately, against the one subtype its `kind` names.
const { $id, ...root } = schema;
ajv.addSchema(
  {
    ...root,
    properties: { ...schema.properties, operations: { type: 'array' } },
  },
  'document',
);

for (const [kind, ref] of Object.entries(mapping)) {
  ajv.addSchema(
    { $schema: schema.$schema, $ref: ref, $defs: schema.$defs },
    kind,
  );
}

const exports = Object.fromEntries(
  ['document', ...kinds].map((name) => [validatorName(name), name]),
);

const banner = `/* eslint-disable */
// @ts-nocheck
// generated by shared/generate_bindings.py
//   source:  circuit.schema.json
//
// A compiled JSON Schema validator, per ADR-0008. Never hand-edited: change the
// schema and regenerate. Untyped by design -- \`serialization/shape.ts\` is the
// typed surface over it, and is where the exports below are given meaning.
//
// \`validateDocument\` checks a circuit with its operations left opaque.
// \`validate<Kind>\` checks one operation against the subtype its kind names.
// Splitting them is load-bearing: see ADR-0008 section 2.

export const OPERATION_DISCRIMINATOR = ${JSON.stringify(propertyName)};
export const OPERATION_KINDS = ${JSON.stringify(kinds)};
`;

// Ajv opens with a "use strict" directive. Once the banner precedes it, it is
// no longer in directive position and becomes a no-op expression -- which
// Prettier then renders as `('use strict');`. ES modules are strict regardless,
// so it is dropped rather than left to read as something meaningful.
const code = standaloneCode(ajv, exports).replace(/^"use strict";\s*/, '');

writeFileSync(outputPath, `${banner}\n${code}`);

/** `document` -> `validateDocument`, `gate` -> `validateGate`. */
function validatorName(name) {
  return `validate${name.charAt(0).toUpperCase()}${name.slice(1)}`;
}
